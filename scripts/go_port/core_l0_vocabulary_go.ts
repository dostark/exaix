#!/usr/bin/env -S deno run -A
/**
 * @module GoPortCoreL0VocabularyGo
 * @path scripts/go_port/core_l0_vocabulary_go.ts
 * @description Generates the Go kept-vocabulary declarations and their reference value table from the pinned vocabulary fixture.
 * Usage: deno run -A scripts/go_port/core_l0_vocabulary_go.ts [--target=<leaf-dir>] [--fixture=<file>]
 */
import { join, resolve } from "@std/path";
import { z } from "zod";
import { argValue } from "./cli_args.ts";
import type { IVocabularySymbolRow } from "./core_l0_vocabulary_symbols.ts";
import type { IGoDeclaration, IGoRender } from "./core_l0_vocabulary_go_types.ts";
import { POINTER_HELPER, renderConstant } from "./core_l0_vocabulary_go_types.ts";

export interface IGoFile {
  readonly name: string;
  readonly content: string;
}

interface IHandwritten {
  readonly types: ReadonlySet<string>;
  readonly consts: ReadonlySet<string>;
  readonly funcs: ReadonlySet<string>;
  readonly typedConsts: ReadonlyMap<string, readonly string[]>;
}

const DEFAULT_LEAF_DIR = join("exaix-go", "internal", "leaf");
const DEFAULT_FIXTURE = join("exaix-go", "internal", "core", "l0", "testdata", "reference", "vocabulary.json");
const GENERATED_HEADER = "// Code generated by the exaix port tooling. DO NOT EDIT.";
const CONSTANTS_FILE = "core_constants_gen.go";
const ENUMS_FILE = "core_enums_gen.go";
const TABLE_FILE = "core_vocabulary_table_gen_test.go";
const GO_FORMAT_COMMAND = "gofmt";

const TYPE_PATTERN = /^type (\w+)/gm;
const FUNC_PATTERN = /^func (\w+)/gm;
const CONST_PATTERN = /^(?:const )?\t?(\w+)(?:\s+(\w+))?\s*=\s*\S/gm;

function isHandwritten(name: string): boolean {
  return name.endsWith(".go") && !name.endsWith("_gen.go") && !name.endsWith("_test.go") &&
    !name.endsWith("_gen_test.go");
}

/** Scans the hand-written leaf files for declared names so generation never duplicates them. */
export async function scanHandwritten(leafDir: string): Promise<IHandwritten> {
  const types = new Set<string>();
  const consts = new Set<string>();
  const funcs = new Set<string>();
  const typedConsts = new Map<string, string[]>();
  for await (const entry of Deno.readDir(leafDir)) {
    if (!entry.isFile || !isHandwritten(entry.name)) continue;
    const source = await Deno.readTextFile(join(leafDir, entry.name));
    for (const m of source.matchAll(TYPE_PATTERN)) types.add(m[1]);
    for (const m of source.matchAll(FUNC_PATTERN)) funcs.add(m[1]);
    for (const m of source.matchAll(CONST_PATTERN)) {
      consts.add(m[1]);
      if (m[2]) typedConsts.set(m[2], [...(typedConsts.get(m[2]) ?? []), m[1]]);
    }
  }
  return { types, consts, funcs, typedConsts };
}

function pascal(raw: string): string {
  const parts = raw.split(/[^A-Za-z0-9]+/).filter((p) => p.length > 0);
  const name = parts
    .map((p) => /^[A-Z0-9]+$/.test(p) ? p[0] + p.slice(1).toLowerCase() : p[0].toUpperCase() + p.slice(1))
    .join("");
  if (!/^[A-Z][A-Za-z0-9]*$/.test(name)) throw new Error(`Cannot derive a Go name from ${raw}`);
  return name;
}

function goName(target: string): string {
  return target.slice(target.lastIndexOf(".") + 1);
}

function enumLabel(typeName: string): string {
  return typeName.replace(/([a-z0-9])([A-Z])/g, "$1 $2").toLowerCase();
}

const ENUM_MEMBERS = z.record(z.string(), z.union([z.string(), z.number()]));
const VOCABULARY_FIXTURE = z.object({
  symbols: z.array(z.object({
    module: z.string(),
    symbol: z.string(),
    kind: z.string(),
    target: z.string(),
    value: z.json(),
  })),
});

function renderEnum(row: IVocabularySymbolRow, name: string): IGoRender {
  const members = Object.entries(ENUM_MEMBERS.parse(row.value));
  const numeric = members.every(([, v]) => z.number().safeParse(v).success);
  const base = numeric ? "int" : "string";
  const consts = members.map(([key, v]) => {
    const literal = numeric ? String(v) : JSON.stringify(v);
    return `\t${name}${pascal(key)} ${name} = ${literal}`;
  });
  const idents = members.map(([key]) => `${name}${pascal(key)}`);
  const parse = numeric ? numericParser(name, idents) : stringParser(name, idents);
  const text = [
    `// ${name} is a closed kept vocabulary set.`,
    `type ${name} ${base}`,
    "",
    `// ${name} values match the kept reference.`,
    "const (",
    ...consts,
    ")",
    "",
    parse,
  ].join("\n");
  return { text, names: [name, ...idents, `Parse${name}`], enumValues: idents, numeric };
}

function stringParser(name: string, idents: readonly string[]): string {
  return [
    `// Parse${name} validates a ${name} string.`,
    `func Parse${name}(raw string) (${name}, error) {`,
    `\treturn parseEnum("${enumLabel(name)}", raw, ${idents.join(", ")})`,
    "}",
  ].join("\n");
}

function numericParser(name: string, idents: readonly string[]): string {
  return [
    `// Parse${name} validates a ${name} number.`,
    `func Parse${name}(raw int) (${name}, error) {`,
    `\tcandidate := ${name}(raw)`,
    `\tif slices.Contains([]${name}{${idents.join(", ")}}, candidate) {`,
    "\t\treturn candidate, nil",
    "\t}",
    `\treturn 0, fmt.Errorf("invalid ${enumLabel(name)} %d", raw)`,
    "}",
  ].join("\n");
}

interface IPlan {
  readonly declarations: IGoDeclaration[];
  readonly constants: string[];
  readonly enums: string[];
  readonly table: string[];
  readonly parsers: string[];
  readonly numericEnum: { value: boolean };
  readonly pointerHelper: { value: boolean };
}

function existingEnumValues(name: string, handwritten: IHandwritten): string[] {
  const idents = handwritten.typedConsts.get(name) ?? [];
  if (idents.length === 0) throw new Error(`Hand-written enum ${name} has no typed constants`);
  return idents.map((i) => `string(${i})`);
}

function planEnum(row: IVocabularySymbolRow, name: string, handwritten: IHandwritten, plan: IPlan): void {
  if (handwritten.types.has(name)) {
    plan.table.push(`\t\t"${name}": []string{${existingEnumValues(name, handwritten).join(", ")}},`);
    if (handwritten.funcs.has(`Parse${name}`)) plan.parsers.push(`\t\t"${name}": wrapParser(Parse${name}),`);
    return;
  }
  const rendered = renderEnum(row, name);
  plan.enums.push(rendered.text);
  plan.declarations.push({ names: rendered.names, source: row.symbol });
  const cast = rendered.numeric ? "int" : "string";
  const values = (rendered.enumValues ?? []).map((i) => `${cast}(${i})`).join(", ");
  plan.table.push(`\t\t"${name}": []${cast}{${values}},`);
  if (rendered.numeric) plan.numericEnum.value = true;
  else plan.parsers.push(`\t\t"${name}": wrapParser(Parse${name}),`);
}

function planConstant(row: IVocabularySymbolRow, name: string, handwritten: IHandwritten, plan: IPlan): void {
  if (handwritten.consts.has(name)) {
    plan.table.push(`\t\t"${name}": ${name},`);
    return;
  }
  const rendered = renderConstant(name, row.value);
  plan.constants.push(rendered.text);
  plan.declarations.push({ names: rendered.names, source: row.symbol });
  if (rendered.usesPointer) plan.pointerHelper.value = true;
  plan.table.push(`\t\t"${name}": ${rendered.tableExpression},`);
}

function assertNoDuplicates(declarations: readonly IGoDeclaration[], handwritten: IHandwritten): void {
  const seen = new Map<string, string>();
  for (const decl of declarations) {
    for (const name of decl.names) {
      const clash = seen.get(name) ??
        (handwritten.types.has(name) || handwritten.consts.has(name) ? "hand-written" : "");
      if (clash) throw new Error(`Generated name ${name} from ${decl.source} clashes with ${clash}`);
      seen.set(name, decl.source);
    }
  }
}

function fileText(imports: readonly string[], body: readonly string[]): string {
  const importBlock = imports.length > 0 ? `\nimport (\n${imports.map((i) => `\t"${i}"`).join("\n")}\n)\n` : "";
  return `${GENERATED_HEADER}\n\npackage leaf\n${importBlock}\n${body.join("\n\n")}\n`;
}

function pointerHelperText(plan: IPlan): string[] {
  if (!plan.pointerHelper.value) return [];
  return [
    `// ${POINTER_HELPER} returns a pointer to a copy of the value.\nfunc ${POINTER_HELPER}[T any](v T) *T { return &v }`,
  ];
}

function tableText(plan: IPlan): string {
  return `${GENERATED_HEADER}

package leaf

// keptVocabularyActual returns the Go value of each kept vocabulary symbol, keyed by its Go name.
func keptVocabularyActual() map[string]any {
	return map[string]any{
${plan.table.join("\n")}
	}
}

// keptEnumParsers returns the string enum parsers, keyed by their Go type name.
func keptEnumParsers() map[string]func(string) (string, error) {
	return map[string]func(string) (string, error){
${plan.parsers.join("\n")}
	}
}
`;
}

/** Builds the generated Go files from the vocabulary fixture rows. */
export function generateVocabularyGo(rows: readonly IVocabularySymbolRow[], handwritten: IHandwritten): IGoFile[] {
  const plan: IPlan = {
    declarations: [],
    constants: [],
    enums: [],
    table: [],
    parsers: [],
    numericEnum: { value: false },
    pointerHelper: { value: false },
  };
  for (const row of rows) {
    const name = goName(row.target);
    if (row.kind === "enum") planEnum(row, name, handwritten, plan);
    else planConstant(row, name, handwritten, plan);
  }
  assertNoDuplicates(plan.declarations, handwritten);
  const enumImports = plan.numericEnum.value ? ["fmt", "slices"] : [];
  return [
    { name: CONSTANTS_FILE, content: fileText([], [...plan.constants, ...pointerHelperText(plan)]) },
    { name: ENUMS_FILE, content: fileText(enumImports, plan.enums) },
    { name: TABLE_FILE, content: tableText(plan) },
  ];
}

async function gofmt(source: string): Promise<string> {
  const command = new Deno.Command(GO_FORMAT_COMMAND, { stdin: "piped", stdout: "piped", stderr: "piped" });
  const child = command.spawn();
  const writer = child.stdin.getWriter();
  await writer.write(new TextEncoder().encode(source));
  await writer.close();
  const output = await child.output();
  if (!output.success) throw new Error(new TextDecoder().decode(output.stderr));
  return new TextDecoder().decode(output.stdout);
}

/** Generates, formats and returns the Go files for the committed fixture and leaf directory. */
export async function buildVocabularyGoFiles(fixturePath: string, leafDir: string): Promise<IGoFile[]> {
  const fixture = VOCABULARY_FIXTURE.parse(JSON.parse(await Deno.readTextFile(fixturePath)));
  const files = generateVocabularyGo(fixture.symbols, await scanHandwritten(leafDir));
  return await Promise.all(files.map(async (f) => ({ name: f.name, content: await gofmt(f.content) })));
}

async function main(args: readonly string[]): Promise<number> {
  const root = resolve(join(import.meta.dirname ?? ".", "..", ".."));
  const leafDir = resolve(argValue(args, "target") ?? join(root, DEFAULT_LEAF_DIR));
  const fixture = resolve(argValue(args, "fixture") ?? join(root, DEFAULT_FIXTURE));
  for (const file of await buildVocabularyGoFiles(fixture, leafDir)) {
    await Deno.writeTextFile(join(leafDir, file.name), file.content);
  }
  console.log(`✅ ${leafDir}`);
  return 0;
}

if (import.meta.main) Deno.exit(await main(Deno.args));
