/**
 * @module CliReference
 * @path apps/exactl/src/docs/cli_reference.ts
 * @description Renders the generated CLI reference from the command tree and the doc records: one page per noun, an index, a JSON manifest and a table for the User Guide.
 * @architectural-layer CLI
 * @dependencies [@exaix/cli, apps/exactl/src/docs/command_tree_walk.ts]
 * @related-files [scripts/generate_cli_reference.ts, apps/exactl/src/command_docs/mod.ts, apps/exactl/tests/generate_cli_reference_test.ts]
 */

import { ExaCtlExitCode, type IExaCtlCommandDoc } from "@exaix/cli";
import type { Opt, Reason } from "@exaix/core/types";
import { ExaCtlCommandGroup, type IExaCtlNounDoc } from "./exactl_noun_doc.ts";
import {
  globalOptionsOf,
  type ICommandTreeNode,
  type ICommandTreeOption,
  type IWalkableRoot,
  walkCommandTree,
} from "./command_tree_walk.ts";

export enum CliEdition {
  SOLO = "solo",
  TEAM = "team",
}

export interface ICliReferenceInput {
  readonly root: IWalkableRoot;
  readonly nounDocs: readonly IExaCtlNounDoc[];
  readonly commandDocs: readonly IExaCtlCommandDoc[];
  readonly edition: CliEdition;
  /** The leaves of the Solo manifest as `plan show` strings. A Team run renders only the leaves outside this set. */
  readonly soloPaths?: Opt<ReadonlySet<string>, Reason.OptionalInput>;
}

export interface ICliReference {
  /** Generated files by name: `index.md`, `<noun>.md` and `exactl-cli.json`. */
  readonly files: ReadonlyMap<string, string>;
  /** A Markdown table of every leaf with its summary and page, for the User Guide. */
  readonly userGuideTable: string;
}

interface IManifestOption {
  flags: string[];
  type?: Opt<string, Reason.OptionalInput>;
  value?: Opt<string, Reason.OptionalInput>;
  default?: Opt<string, Reason.OptionalInput>;
  required: boolean;
  description: string;
}

interface IManifestCommand {
  path: string[];
  summary: string;
  description: string;
  arguments: Array<{ name: string; optional: boolean; variadic: boolean }>;
  options: IManifestOption[];
  examples: Array<{ title: string; command: string }>;
  output: string;
  exit_codes: Array<{ code: number; name: string }>;
  see_also: string[];
  edition?: Opt<string, Reason.OptionalInput>;
}

/** A documented leaf: its tree node joined with its doc record. */
interface ILeaf {
  readonly node: ICommandTreeNode;
  readonly doc: IExaCtlCommandDoc;
}

const TITLE_KEY = "title";
const DESCRIPTION_KEY = "description";
const MANIFEST_VERSION = 1;
const MANIFEST_FILE = "exactl-cli.json";
const INDEX_FILE = "index.md";
const GENERATED_NOTE = "<!-- Generated by `deno task docs:cli`. Do not edit. -->";
const NEWLINE = "\n";
const BLOCK_BREAK = "\n\n";
const COMMAND_PROGRAM = "exactl";
const OTHER_GROUP = "Other";
const WORD_JOINER = " ";
const MANIFEST_INDENT = 2;
const CODE_FENCE = "```";
const EDITION_TEAM_LABEL = "Team";
const SOLO_REFERENCE_DIR = "../../../docs/cli/";
const SOLO_REFERENCE_LINK = `${SOLO_REFERENCE_DIR}index.md`;

function pathKey(path: readonly string[]): string {
  return path.join(WORD_JOINER);
}

function pageName(noun: string): string {
  return `${noun}.md`;
}

/** The anchor that a Markdown viewer builds from the heading `## exactl <path>`. */
function anchorOf(path: readonly string[]): string {
  return [COMMAND_PROGRAM, ...path].join("-");
}

function quoted(value: string): string {
  return JSON.stringify(value);
}

function frontMatter(fields: ReadonlyArray<readonly [string, string]>): string {
  const lines = fields.map(([key, value]) => `${key}: ${value}`);
  return ["---", ...lines, "---"].join(NEWLINE);
}

function usageOf(leaf: ILeaf): string {
  const args = leaf.node.args.map((arg) => {
    const name = arg.variadic ? `${arg.name}...` : arg.name;
    return arg.optional ? `[${name}]` : `<${name}>`;
  });
  const options = leaf.node.options.some((option) => !option.hidden) ? ["[options]"] : [];
  return [COMMAND_PROGRAM, ...leaf.node.path, ...options, ...args].join(WORD_JOINER);
}

function flagText(option: ICommandTreeOption): string {
  const value = option.takesValue ? ` <${option.valueName ?? "value"}>` : "";
  return `${option.flags.join(", ")}${value}`;
}

function optionLine(option: ICommandTreeOption): string {
  const notes = [
    ...(option.valueType !== undefined ? [`type: ${option.valueType}`] : []),
    ...(option.defaultValue !== undefined ? [`default: \`${option.defaultValue}\``] : []),
    ...(option.required ? ["required"] : []),
  ];
  const suffix = notes.length > 0 ? ` (${notes.join(", ")})` : "";
  return `- \`${flagText(option)}\`: ${option.description}${suffix}`;
}

function linkTo(command: string, fromPage: Opt<string, Reason.OptionalInput>): string {
  const path = command.split(WORD_JOINER).slice(1);
  const page = `${fromPage ?? ""}${pageName(path[0])}`;
  return path.length > 1 ? `[${command}](${page}#${anchorOf(path)})` : `[${command}](${page})`;
}

function leafSection(
  leaf: ILeaf,
  edition: CliEdition,
  soloPaths: Opt<ReadonlySet<string>, Reason.OptionalInput>,
): string {
  const { doc } = leaf;
  const parts = [
    `## ${COMMAND_PROGRAM} ${pathKey(leaf.node.path)}`,
    doc.summary,
    doc.description,
    `**Usage:** \`${usageOf(leaf)}\``,
  ];
  if (edition === CliEdition.TEAM) parts.push(`**Edition:** ${EDITION_TEAM_LABEL}.`);
  const options = leaf.node.options.filter((option) => !option.hidden);
  if (leaf.node.args.length > 0) {
    parts.push(
      [
        "**Arguments**",
        leaf.node.args.map((arg) =>
          `- \`${arg.name}\`${arg.optional ? " (optional)" : ""}${arg.variadic ? " (repeatable)" : ""}`
        )
          .join(NEWLINE),
      ].join(BLOCK_BREAK),
    );
  }
  if (options.length > 0) parts.push(["**Options**", options.map(optionLine).join(NEWLINE)].join(BLOCK_BREAK));
  parts.push(
    [
      "**Examples**",
      ...doc.examples.map((example) =>
        [`${example.title}:`, [`${CODE_FENCE}bash`, example.command, CODE_FENCE].join(NEWLINE)].join(BLOCK_BREAK)
      ),
    ].join(BLOCK_BREAK),
  );
  parts.push(`**Output:** ${doc.output}.`);
  parts.push(
    ["**Exit codes**", doc.exitCodes.map((code) => `- ${ExaCtlExitCode[code]} (${code})`).join(NEWLINE)].join(
      BLOCK_BREAK,
    ),
  );
  if (doc.seeAlso.length > 0) {
    parts.push(
      `**See also:** ${
        doc.seeAlso.map((command) =>
          linkTo(command, soloPaths?.has(command.slice(COMMAND_PROGRAM.length + 1)) ? SOLO_REFERENCE_DIR : undefined)
        ).join(", ")
      }`,
    );
  }
  return parts.join(BLOCK_BREAK);
}

function manifestEntry(leaf: ILeaf, edition: CliEdition): IManifestCommand {
  const entry: IManifestCommand = {
    path: leaf.node.path,
    summary: leaf.doc.summary,
    description: leaf.doc.description,
    arguments: leaf.node.args,
    options: leaf.node.options.filter((option) => !option.hidden).map((option) => ({
      flags: option.flags,
      type: option.valueType,
      value: option.valueName,
      default: option.defaultValue,
      required: option.required,
      description: option.description,
    })),
    examples: leaf.doc.examples.map((example) => ({ title: example.title, command: example.command })),
    output: leaf.doc.output,
    exit_codes: leaf.doc.exitCodes.map((code) => ({ code, name: ExaCtlExitCode[code] })),
    see_also: [...leaf.doc.seeAlso],
  };
  if (edition === CliEdition.TEAM) entry.edition = edition;
  return entry;
}

function renderTable(headers: readonly string[], rows: readonly (readonly string[])[]): string {
  const widths = headers.map((header, column) => Math.max(header.length, ...rows.map((row) => row[column].length)));
  const line = (cells: readonly string[]) =>
    `| ${cells.map((cell, column) => cell.padEnd(widths[column])).join(" | ")} |`;
  const separator = `| ${widths.map((width) => "-".repeat(width)).join(" | ")} |`;
  return [line(headers), separator, ...rows.map(line)].join(NEWLINE);
}

function groupOf(noun: Opt<IExaCtlNounDoc, Reason.OptionalInput>): string {
  return noun?.group ?? OTHER_GROUP;
}

function nounPage(
  noun: string,
  nounDoc: Opt<IExaCtlNounDoc, Reason.OptionalInput>,
  leaves: readonly ILeaf[],
  order: number,
  edition: CliEdition,
  soloPaths: Opt<ReadonlySet<string>, Reason.OptionalInput>,
): string {
  const summary = nounDoc?.summary ?? leaves[0].doc.summary;
  const fields: Array<readonly [string, string]> = [
    [TITLE_KEY, quoted(`${COMMAND_PROGRAM} ${noun}`)],
    [DESCRIPTION_KEY, quoted(summary)],
    ["group", quoted(groupOf(nounDoc))],
    ["order", String(order)],
  ];
  if (edition === CliEdition.TEAM) fields.push(["edition", quoted(edition)]);
  const intro = nounDoc === undefined ? [] : [nounDoc.description];
  const lifecycle = nounDoc !== undefined && nounDoc.lifecycle.length > 0
    ? [`Lifecycle: ${nounDoc.lifecycle.join(" → ")}`]
    : [];
  return [
    frontMatter(fields),
    GENERATED_NOTE,
    `# ${COMMAND_PROGRAM} ${noun}`,
    ...intro,
    ...lifecycle,
    ...leaves.map((leaf) => leafSection(leaf, edition, soloPaths)),
  ].join(BLOCK_BREAK) + NEWLINE;
}

function indexPage(
  input: ICliReferenceInput,
  nouns: ReadonlyArray<{ noun: string; doc: Opt<IExaCtlNounDoc, Reason.OptionalInput>; summary: string }>,
  solo: boolean,
): string {
  const groups = [...Object.values(ExaCtlCommandGroup), OTHER_GROUP];
  const sections = groups.flatMap((group) => {
    const members = nouns.filter((entry) => groupOf(entry.doc) === group);
    if (members.length === 0) return [];
    return [
      [
        `## ${group}`,
        members.map((entry) => `- [${entry.noun}](${pageName(entry.noun)}): ${entry.summary}`).join(NEWLINE),
      ]
        .join(BLOCK_BREAK),
    ];
  });
  const globals = globalOptionsOf(input.root).filter((option) => !option.hidden);
  const teamNote = solo ? [] : [
    `The commands below exist in the Team edition only. The [Solo command reference](${SOLO_REFERENCE_LINK}) lists the other commands.`,
  ];
  return [
    frontMatter([
      [TITLE_KEY, quoted(solo ? "exactl command reference" : "exactl Team command reference")],
      [DESCRIPTION_KEY, quoted("Every exactl command with its options, examples and exit codes")],
    ]),
    GENERATED_NOTE,
    `# ${solo ? "exactl command reference" : "exactl Team command reference"}`,
    ...teamNote,
    ...sections,
    ...(solo ? [["## Global options", globals.map(optionLine).join(NEWLINE)].join(BLOCK_BREAK)] : []),
  ].join(BLOCK_BREAK) + NEWLINE;
}

/** Renders the reference of one edition. A Team run renders only the leaves that the Solo manifest lacks. */
export function renderCliReference(input: ICliReferenceInput): ICliReference {
  const solo = input.edition === CliEdition.SOLO;
  const docs = new Map(input.commandDocs.map((doc) => [pathKey(doc.path), doc]));
  const leaves: ILeaf[] = walkCommandTree(input.root).flatMap((node) => {
    const doc = docs.get(pathKey(node.path));
    if (doc === undefined || node.hidden) return [];
    if (!solo && input.soloPaths?.has(pathKey(node.path))) return [];
    return [{ node, doc }];
  });
  const nounNames = [...new Set(leaves.map((leaf) => leaf.node.path[0]))];
  const orderOf = (noun: string) => {
    const index = input.nounDocs.findIndex((doc) => doc.noun === noun);
    return index === -1 ? input.nounDocs.length + 1 : index + 1;
  };
  nounNames.sort((a, b) => orderOf(a) - orderOf(b));
  const nouns = nounNames.map((noun) => {
    const doc = input.nounDocs.find((candidate) => candidate.noun === noun);
    const members = leaves.filter((leaf) => leaf.node.path[0] === noun);
    return { noun, doc, members, summary: doc?.summary ?? members[0].doc.summary };
  });
  const files = new Map<string, string>();
  files.set(INDEX_FILE, indexPage(input, nouns, solo));
  for (const entry of nouns) {
    files.set(
      pageName(entry.noun),
      nounPage(entry.noun, entry.doc, entry.members, orderOf(entry.noun), input.edition, input.soloPaths),
    );
  }
  const manifest = {
    version: MANIFEST_VERSION,
    edition: input.edition,
    commands: leaves.map((leaf) => manifestEntry(leaf, input.edition)),
  };
  files.set(MANIFEST_FILE, JSON.stringify(manifest, null, MANIFEST_INDENT) + NEWLINE);
  const userGuideTable = renderTable(
    ["Command", "Summary", "Page"],
    leaves.map((leaf) => [
      `\`${COMMAND_PROGRAM} ${pathKey(leaf.node.path)}\``,
      leaf.doc.summary,
      `[${leaf.node.path[0]}](cli/${pageName(leaf.node.path[0])}${
        leaf.node.path.length > 1 ? `#${anchorOf(leaf.node.path)}` : ""
      })`,
    ]),
  );
  return { files, userGuideTable };
}
